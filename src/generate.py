"""Generation: pluggable LLM with an offline extractive fallback.

If ANTHROPIC_API_KEY is set, answers are generated by a Claude model grounded in
retrieved context. Otherwise a deterministic extractive fallback returns the
single most relevant sentence from the top retrieved doc. The fallback keeps
the whole harness reproducible with zero API keys, so tests and CI run offline.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass

from .index import Index, search
from . import config as C


@dataclass
class Generation:
    answer: str
    context_doc_ids: list[str]
    used_llm: bool


def _split_sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+", text.strip())
    return [p.strip() for p in parts if p.strip()]


def _tokens(s: str) -> set[str]:
    return set(re.findall(r"[a-z0-9]+", s.lower()))


def _extractive(query: str, context: list[tuple[str, float]], index: Index) -> str:
    """Return the sentence from the top retrieved doc that best matches the query."""
    if not context:
        return ""
    top_doc = context[0][0]
    text = index.texts[index.doc_ids.index(top_doc)]
    qtok = _tokens(query)
    best, best_score = "", -1.0
    for sent in _split_sentences(text):
        stok = _tokens(sent)
        if not stok:
            continue
        overlap = len(qtok & stok) / (len(qtok) or 1)
        if overlap > best_score:
            best, best_score = sent, overlap
    return best or _split_sentences(text)[0]


def _llm(query: str, context: list[tuple[str, float]], index: Index) -> str:
    import anthropic  # imported lazily; only when key is set
    docs = "\n\n".join(
        f"[{i+1}] {index.texts[index.doc_ids.index(did)]}" for did, _ in context
    )
    prompt = (
        f"Answer the question using only the context below. Be concise.\n\n"
        f"Context:\n{docs}\n\nQuestion: {query}\n\nAnswer:"
    )
    client = anthropic.Anthropic()
    msg = client.messages.create(
        model=C.MODEL,
        max_tokens=300,
        messages=[{"role": "user", "content": prompt}],
    )
    return msg.content[0].text.strip()


def generate(query: str, index: Index, top_k: int = 5, force_offline: bool = False) -> Generation:
    context = search(index, query, top_k=top_k)
    use_llm = (not force_offline) and bool(os.getenv("ANTHROPIC_API_KEY"))
    if use_llm:
        try:
            ans = _llm(query, context, index)
            return Generation(answer=ans, context_doc_ids=[d for d, _ in context], used_llm=True)
        except Exception as e:  # fall back if the API call fails
            print(f"[llm failed: {e}; using extractive fallback]")
    ans = _extractive(query, context, index)
    return Generation(answer=ans, context_doc_ids=[d for d, _ in context], used_llm=False)
